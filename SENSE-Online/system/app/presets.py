def make_presets():
    result = []
    for group_index, category in enumerate(CATEGORIES):
        original = TEXTS[category].strip().splitlines()
        additional = ADDITIONS[category].strip().splitlines()
        assert len(original) == len(additional) == 50, (category, len(original), len(additional))
        rows = original + additional
        for index, row in enumerate(rows, 1):
            fields = row.split('|')
            text, unit = fields[-2:]
            qid = fields[0] if len(fields) == 3 else f'sense-{group_index + 1}-{index:02d}'
            upper = 100 if unit == '％' or text.startswith('日本の大人100人') else 24 if unit == '時' else None
            if '100点満点' in text or '最高難度を100' in text:
                upper = 100
            elif '1週間のうち' in text:
                upper = 7
            elif '自由に使える1万円' in text:
                upper = 10000
            elif '1週間だけ休暇' in text:
                upper = 7
            elif '1時間ラジオ番組' in text:
                upper = 60
            elif '休日が1日増えたら' in text:
                upper = 24
            result.append(dict(id=qid, text=text, category=category, unit=unit,
                               allow_decimal=unit in ('時間', 'km', 'kg', '℃', '年'),
                               min_value=0, max_value=upper, source_type='preset'))
    return result


PRESETS = make_presets()
ORIGINAL_PRESETS, ADDITIONAL_PRESETS = [], []
for category in CATEGORIES:
    group = [q for q in PRESETS if q['category'] == category]
    ORIGINAL_PRESETS.extend(group[:50])
    ADDITIONAL_PRESETS.extend(group[50:])


def seed_library(store):
    # Preserve edits and deletions from the original library when adding v2.
    store.seed_questions(ORIGINAL_PRESETS, 'four-genres-200-v1', LEGACY_CATEGORIES)
    store.seed_questions(ADDITIONAL_PRESETS, 'four-genres-400-v1', LEGACY_CATEGORIES)


def draw_choices(questions, used_ids=(), previous=()):
    """One per genre; only published questions count as used. Prefer a new draw."""
    used, old = set(used_ids), {q['id'] for q in previous}
    result = []
    for category in CATEGORIES:
        pool = [q for q in questions if q['id'] not in used and
                LEGACY_CATEGORIES.get(q['category'], q['category']) == category]
        fresh = [q for q in pool if q['id'] not in old]
        if pool:
            result.append(dict(secrets.choice(fresh or pool), category=category))
    return result
